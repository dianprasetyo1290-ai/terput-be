CREATE OR REPLACE FUNCTION payroll_lines_guard_final() RETURNS trigger AS $$
DECLARE st TEXT;
BEGIN
    SELECT status INTO st FROM payroll_runs WHERE id = COALESCE(OLD.run_id, NEW.run_id);
    IF st = 'final' THEN
        IF TG_OP = 'DELETE' THEN
            RAISE EXCEPTION 'payroll run final tidak dapat diubah';
        END IF;
        IF (NEW.gross_idr, NEW.taxable_idr, NEW.bpjs_base_idr, NEW.bpjs_employee_idr, NEW.bpjs_employer_idr,
            NEW.pph21_idr, NEW.other_deductions_idr, NEW.net_idr, NEW.details, NEW.employee_id, NEW.run_id)
           IS DISTINCT FROM
           (OLD.gross_idr, OLD.taxable_idr, OLD.bpjs_base_idr, OLD.bpjs_employee_idr, OLD.bpjs_employer_idr,
            OLD.pph21_idr, OLD.other_deductions_idr, OLD.net_idr, OLD.details, OLD.employee_id, OLD.run_id) THEN
            RAISE EXCEPTION 'payroll run final tidak dapat diubah';
        END IF;
    END IF;
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_payroll_lines_guard_final ON payroll_lines;
CREATE TRIGGER trg_payroll_lines_guard_final
    BEFORE UPDATE OR DELETE ON payroll_lines
    FOR EACH ROW EXECUTE FUNCTION payroll_lines_guard_final();

