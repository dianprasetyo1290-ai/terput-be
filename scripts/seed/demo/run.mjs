// Writes the SQL of every demo data generator to <outDir>/<NN>_<database>.sql
// (one file per generator and database, applied in name order by
// scripts/seed-demo.sh).
//
//   node scripts/seed/demo/run.mjs <outDir> [generator-number ...]
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const [outDir, ...only] = process.argv.slice(2)
if (!outDir) {
  console.error('usage: node run.mjs <outDir> [NN ...]')
  process.exit(1)
}
fs.mkdirSync(outDir, { recursive: true })

const generators = fs.readdirSync(here).filter((f) => /^\d\d_.+\.mjs$/.test(f)).sort()
for (const g of generators) {
  const nn = g.slice(0, 2)
  if (only.length && !only.includes(nn)) continue
  const { generate } = await import(pathToFileURL(path.join(here, g)).href)
  for (const [db, sql] of Object.entries(await generate())) {
    if (!sql.trim()) continue
    const file = path.join(outDir, `${nn}_${db}.sql`)
    fs.writeFileSync(file, `-- generated by scripts/seed/demo/${g}\nBEGIN;\n${sql}\nCOMMIT;\n`)
    console.log(`${path.basename(file).padEnd(36)} ${(sql.length / 1024).toFixed(0)} KB`)
  }
}
